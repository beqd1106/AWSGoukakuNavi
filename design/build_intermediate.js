// ---- 正解位置をローテーションで①〜④へ均等分散 ----
function rotate(item, t) {
  if (t === 0) return item;
  const n = item.choices.length; // 4
  const newChoices = new Array(n);
  for (let j = 0; j < n; j++) newChoices[(j + t) % n] = item.choices[j];
  const newCorrect = item.correctAnswers.map((c) => (c + t) % n);
  const newWrong = {};
  for (const [k, v] of Object.entries(item.wrongChoiceExplanations)) {
    newWrong[String((Number(k) + t) % n)] = v;
  }
  return { ...item, choices: newChoices, correctAnswers: newCorrect, wrongChoiceExplanations: newWrong };
}
